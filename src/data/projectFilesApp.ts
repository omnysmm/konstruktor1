// utils/exportHTML.ts (упрощённая версия)
projectFiles['src/utils/exportHTML.ts'] = [
  "import { Template } from '../types';",
  "",
  "export function exportTemplateToHTML(template: Template): string {",
  "  const { colors, sections, name } = template;",
  "  const sectionsHTML = sections.map(s => {",
  "    const c = s.content;",
  "    switch (s.type) {",
  "      case 'hero':",
  "        return '<section style=\"background:linear-gradient(135deg,' + colors.primary + ',' + colors.secondary + ');min-height:80vh;display:flex;align-items:center;justify-content:center\"><div style=\"text-align:center;padding:5rem 1rem\"><h1 style=\"color:' + colors.text + ';font-size:3.5rem;font-weight:800;margin-bottom:1.5rem\">' + c.title + '</h1><p style=\"color:' + colors.text + ';opacity:.85;font-size:1.25rem;margin-bottom:2.5rem\">' + c.subtitle + '</p><a href=\"#\" style=\"background:' + colors.accent + ';color:#fff;padding:1rem 2rem;border-radius:.75rem;font-weight:600;text-decoration:none;display:inline-block\">' + c.ctaText + '</a></div></section>';",
  "      case 'footer':",
  "        return '<footer style=\"padding:4rem 1rem;background:' + colors.primary + '\"><div style=\"max-width:1200px;margin:0 auto;text-align:center\"><h3 style=\"font-size:1.25rem;font-weight:700;color:#fff;margin-bottom:.75rem\">' + c.companyName + '</h3><p style=\"color:rgba(255,255,255,.6)\">' + c.description + '</p></div></footer>';",
  "      default:",
  "        return '<section style=\"padding:5rem 1rem;background:' + colors.background + '\"><div style=\"max-width:1200px;margin:0 auto;text-align:center\"><h2 style=\"color:' + colors.text + ';font-size:2rem;font-weight:700\">' + (c.title || '') + '</h2></div></section>';",
  "    }",
  "  }).join('\\n');",
  "",
  "  return '<!DOCTYPE html><html lang=\"ru\"><head><meta charset=\"UTF-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1.0\"><title>' + name + '</title><style>*,*::before,*::after{box-sizing:border-box;margin:0;padding:0}body{font-family:-apple-system,BlinkMacSystemFont,Segoe UI,Roboto,sans-serif;line-height:1.6}</style></head><body>' + sectionsHTML + '</body></html>';",
  "}",
  "",
  "export function downloadHTML(html: string, filename: string) {",
  "  const blob = new Blob([html], { type: 'text/html;charset=utf-8' });",
  "  const url = URL.createObjectURL(blob);",
  "  const a = document.createElement('a');",
  "  a.href = url;",
  "  a.download = filename;",
  "  document.body.appendChild(a);",
  "  a.click();",
  "  document.body.removeChild(a);",
  "  URL.revokeObjectURL(url);",
  "}",
].join('\n');
